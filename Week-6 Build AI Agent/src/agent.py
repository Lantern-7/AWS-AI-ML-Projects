"""
src/agent.py - The Autonomous ReAct Agent Loop with High-Demand Resilience.

Features:
1. Multi-model fallback: Automatically tries gemini-2.5-flash and gemini-flash-lite-latest if Google servers return 503.
2. Verified Gemini functionResponse schema with role: "user".
3. ReAct loop governor (MAX_STEPS = 6).
"""

import os
import json
import time
import urllib.request
import urllib.error
from typing import Dict, Any, List
from dotenv import load_dotenv

from src.tools import get_weather_forecast, get_city_activities, save_travel_plan
from src.prompts import SYSTEM_INSTRUCTION, TOOLS_SCHEMA

load_dotenv()


class TravelAgent:
    def __init__(self, primary_model: str = "gemini-flash-lite-latest", max_steps: int = 6):        
        self.api_key = os.getenv("GEMINI_API_KEY")
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY environment variable is missing. Check your .env file.")
        
        # Fallback cascade in case one model is overloaded (503)
        self.candidate_models = [
            "gemini-flash-lite-latest",
            "gemini-3.8-flash"
        ]
        self.active_model = primary_model
        self.max_steps = max_steps
        
        # Tool dispatch table
        self.tool_map = {
            "get_weather_forecast": get_weather_forecast,
            "get_city_activities": get_city_activities,
            "save_travel_plan": save_travel_plan
        }

    def _call_gemini_api(self, contents: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Sends conversation history to Gemini, auto-falling back if a model returns 503 or 404."""
        payload = {
            "contents": contents,
            "tools": TOOLS_SCHEMA,
            "systemInstruction": {
                "parts": [{"text": SYSTEM_INSTRUCTION}]
            },
            "generationConfig": {
                "temperature": 0.2
            }
        }

        last_error = None
        for model in self.candidate_models:
            endpoint = (
                f"https://generativelanguage.googleapis.com/v1beta/models/"
                f"{model}:generateContent?key={self.api_key}"
            )
            req = urllib.request.Request(
                endpoint,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"}
            )

            try:
                with urllib.request.urlopen(req, timeout=30) as response:
                    self.active_model = model
                    return json.loads(response.read().decode("utf-8"))
            except urllib.error.HTTPError as e:
                err_text = e.read().decode("utf-8")
                # If server is overloaded (503) or model unavailable (404), try next model
                if e.code in [503, 404]:
                    print(f"⚠️ Model '{model}' returned HTTP {e.code} (High demand/unavailable). Trying backup model...")
                    time.sleep(1)
                    last_error = err_text
                    continue
                else:
                    print(f"\n❌ Google Gemini API Error:\n{err_text}\n")
                    raise e
            except Exception as e:
                last_error = str(e)
                continue

        raise RuntimeError(f"All candidate models are temporarily unavailable: {last_error}")

    def run(self, user_request: str) -> str:
        """
        Executes the ReAct agent loop:
        Thought -> Tool Call -> Tool Execution -> Observation -> Final Answer.
        """
        print(f"\n{'='*70}")
        print(f"🎯 USER REQUEST: {user_request}")
        print(f"{'='*70}\n")

        contents = [
            {
                "role": "user",
                "parts": [{"text": user_request}]
            }
        ]

        for step in range(1, self.max_steps + 1):
            print(f"🔄 [Step {step}/{self.max_steps}] Agent reasoning...")

            try:
                response = self._call_gemini_api(contents)
            except Exception as e:
                return f"❌ Agent communication error: {str(e)}"

            candidates = response.get("candidates", [])
            if not candidates:
                return "❌ No response candidate generated by Gemini."

            candidate_content = candidates[0].get("content", {})
            parts = candidate_content.get("parts", [])

            # Extract any function call and textual thoughts
            function_call = None
            text_response = ""

            for part in parts:
                if "functionCall" in part:
                    function_call = part["functionCall"]
                if "text" in part:
                    text_response += part["text"]

            # If no tool was called, the agent has completed its mission!
            if not function_call:
                print(f"\n✅ Agent has completed its mission (Powered by {self.active_model})!\n")
                return text_response.strip()

            # Record model's functionCall turn into conversation history
            contents.append({
                "role": "model",
                "parts": candidate_content.get("parts", [{"functionCall": function_call}])
            })

            # Retrieve function name and arguments
            fn_name = function_call.get("name", "")
            fn_args = function_call.get("args", {})

            print(f"🛠️  [TOOL ACTION] Calling '{fn_name}'")
            print(f"    Parameters: {json.dumps(fn_args, indent=2)}")

            # Execute the tool
            tool_func = self.tool_map.get(fn_name)
            if not tool_func:
                tool_result = {"error": f"Unknown tool: '{fn_name}'"}
            else:
                try:
                    tool_result = tool_func(**fn_args)
                except Exception as err:
                    tool_result = {"error": f"Execution failed: {str(err)}"}

            status = tool_result.get("status", "done")
            print(f"👀 [OBSERVATION] Tool '{fn_name}' status: {status}\n")

            # Feed tool response back to Gemini (Role MUST be 'user')
            contents.append({
                "role": "user",
                "parts": [
                    {
                        "functionResponse": {
                            "name": fn_name,
                            "response": {
                                "name": fn_name,
                                "content": tool_result
                            }
                        }
                    }
                ]
            })

        return "⚠️ Reached maximum step limit before completing all tasks."