# Cell 3: The Agent's Toolset (Zero Hardcoding)
import os
import json
import urllib.request
import urllib.parse
from typing import Dict, Any, List

def geocode_location(place_name: str) -> Dict[str, Any]:
    """Dynamically resolves any place name to lat/lon using Open-Meteo Geocoding API."""
    query = urllib.parse.quote(place_name.strip())
    url = f"https://geocoding-api.open-meteo.com/v1/search?name={query}&count=1&language=en&format=json"
    req = urllib.request.Request(url, headers={"User-Agent": "TravelAgent/1.0"})
    with urllib.request.urlopen(req, timeout=6) as response:
        data = json.loads(response.read().decode("utf-8"))

    results = data.get("results")
    if not results:
        raise ValueError(f"Could not locate '{place_name}'.")
    top = results[0]
    return {
        "name": top.get("name"),
        "country": top.get("country", ""),
        "latitude": top.get("latitude"),
        "longitude": top.get("longitude")
    }

def get_weather_forecast(city: str, days: int = 3) -> Dict[str, Any]:
    """Live weather forecast using coordinates and Open-Meteo."""
    days = max(1, min(int(days), 14))
    try:
        geo = geocode_location(city)
        lat, lon = geo["latitude"], geo["longitude"]
        url = (
            f"https://api.open-meteo.com/v1/forecast?"
            f"latitude={lat}&longitude={lon}&"
            f"daily=temperature_2m_max,temperature_2m_min,precipitation_probability_max&"
            f"forecast_days={days}&timezone=auto"
        )
        req = urllib.request.Request(url, headers={"User-Agent": "TravelAgent/1.0"})
        with urllib.request.urlopen(req, timeout=6) as response:
            data = json.loads(response.read().decode("utf-8"))

        daily = data.get("daily", {})
        highs = daily.get("temperature_2m_max", [])
        lows = daily.get("temperature_2m_min", [])
        rains = daily.get("precipitation_probability_max", [])

        avg_high = sum(highs)/len(highs) if highs else 25.0
        avg_low = sum(lows)/len(lows) if lows else 18.0
        max_rain = max(rains) if rains else 0

        condition = "Hot & Sunny" if avg_high > 28 else ("Mild" if avg_high > 18 else "Cold")
        if max_rain > 50:
            condition += " with expected rain"

        return {
            "status": "success",
            "resolved_location": f"{geo['name']}, {geo['country']}",
            "forecast_days": days,
            "overall_climate": condition,
            "avg_high_c": round(avg_high, 1),
            "avg_low_c": round(avg_low, 1),
            "max_rain_probability": max_rain
        }
    except Exception as e:
        return {"status": "error", "message": str(e)}

def get_city_activities(city: str, theme: str = "refreshment", num_days: int = 3) -> Dict[str, Any]:
    """Discovers live verified sights using Wikipedia Search API."""
    num_days = max(1, min(int(num_days), 7))
    search_term = urllib.parse.quote(f"{city} tourism {theme} attractions")
    url = f"https://en.wikipedia.org/w/api.php?action=query&list=search&srsearch={search_term}&utf8=&format=json&srlimit=5"

    try:
        req = urllib.request.Request(url, headers={"User-Agent": "EducationalAgent/1.0"})
        with urllib.request.urlopen(req, timeout=6) as response:
            data = json.loads(response.read().decode("utf-8"))

        items = data.get("query", {}).get("search", [])
        activities = []
        for it in items:
            clean_snippet = it.get("snippet", "").replace('<span class="searchmatch">', '').replace('</span>', '')
            activities.append({"name": it.get("title"), "description": clean_snippet[:150] + "..."})

        return {"status": "success", "city": city, "theme": theme, "attractions": activities}
    except Exception as e:
        return {"status": "error", "message": str(e)}

def save_travel_plan(filename: str, content: str) -> Dict[str, Any]:
    """Saves the markdown plan to disk."""
    safe_name = os.path.basename(filename.strip())
    if not safe_name.endswith((".md", ".txt")):
        safe_name += ".md"
    os.makedirs("outputs", exist_ok=True)
    path = os.path.join("outputs", safe_name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    return {"status": "success", "saved_path": path, "filename": safe_name}

