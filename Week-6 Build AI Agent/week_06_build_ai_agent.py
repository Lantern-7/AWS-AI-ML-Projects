# Cell 4: System Prompt, Gemini OpenAPI Tool Schemas, and ReAct Engine (Verified)
import os
import json
import time
import urllib.request
import urllib.error

SYSTEM_INSTRUCTION = """
You are an elite Autonomous Travel & Packing Concierge Agent.
RULES:
1. Carefully inspect the user's prompt for: destination, duration, purpose (e.g. business, safari, relaxation), and any special requests.
2. Only call tools requested by the user. If they only ask for packing, do NOT call activity recommendations.
3. If they ask for activities, refreshment, or sights, call `get_city_activities`.
4. Always call `save_travel_plan` to export a comprehensive markdown travel guide before finishing.
"""

TOOLS_SCHEMA = [
    {
        "function_declarations": [
            {
                "name": "get_weather_forecast",
                "description": "Fetches live weather forecast for any city worldwide.",
                "parameters": {
                    "type": "OBJECT",
                    "properties": {
                        "city": {"type": "STRING", "description": "City or country name."},
                        "days": {"type": "INTEGER", "description": "Number of days (1-14)."}
                    },
                    "required": ["city"]
                }
            },
            {
                "name": "get_city_activities",
                "description": "Finds tourist attractions and relaxation ideas for any city in the world.",
                "parameters": {
                    "type": "OBJECT",
                    "properties": {
                        "city": {"type": "STRING", "description": "Target city name."},
                        "theme": {"type": "STRING", "description": "Theme like 'refreshment', 'relaxation', or 'culture'."},
                        "num_days": {"type": "INTEGER", "description": "Number of days (1-7)."}
                    },
                    "required": ["city"]
                }
            },
            {
                "name": "save_travel_plan",
                "description": "Saves the completed markdown travel plan to disk.",
                "parameters": {
                    "type": "OBJECT",
                    "properties": {
                        "filename": {"type": "STRING", "description": "Filename, e.g. 'trip_plan.md'."},
                        "content": {"type": "STRING", "description": "Full markdown content."}
                    },
                    "required": ["filename", "content"]
                }
            }
        ]
    }
]

class TravelAgent:
    def __init__(self, primary_model: str = "gemini-flash-lite-latest", max_steps: int = 6):
        self.api_key = os.environ.get("GEMINI_API_KEY")
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY environment variable is not set!")

        self.candidate_models = [
            primary_model,
            "gemini-flash-lite-latest",
            "gemini-3.8-flash"
        ]
        self.active_model = primary_model
        self.max_steps = max_steps
        self.tools = {
            "get_weather_forecast": get_weather_forecast,
            "get_city_activities": get_city_activities,
            "save_travel_plan": save_travel_plan
        }

    def _call_gemini(self, contents):
        payload = {
            "contents": contents,
            "tools": TOOLS_SCHEMA,
            "systemInstruction": {"parts": [{"text": SYSTEM_INSTRUCTION}]},
            "generationConfig": {"temperature": 0.2}
        }

        last_error = None
        for model in self.candidate_models:
            endpoint = (
                f"https://generativelanguage.googleapis.com/v1beta/models/"
                f"{model}:generateContent?key={self.api_key}"
            )
            req = urllib.request.Request(
                endpoint,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"}
            )
            try:
                with urllib.request.urlopen(req, timeout=30) as res:
                    self.active_model = model
                    return json.loads(res.read().decode("utf-8"))
            except urllib.error.HTTPError as e:
                err_body = e.read().decode("utf-8")
                if e.code in [503, 404]:
                    print(f"⚠️ Model '{model}' unavailable (HTTP {e.code}). Switching...")
                    time.sleep(1)
                    last_error = err_body
                    continue
                else:
                    print(f"\n❌ Gemini API Error: {err_body}\n")
                    raise e
            except Exception as e:
                last_error = str(e)
                continue

        raise RuntimeError(f"All models failed: {last_error}")

    def run(self, user_request: str) -> str:
        print(f"🎯 USER REQUEST: {user_request}\n" + "-"*60)
        contents = [{"role": "user", "parts": [{"text": user_request}]}]

        for step in range(1, self.max_steps + 1):
            print(f"🔄 [Step {step}/{self.max_steps}] Reasoning...")
            res = self._call_gemini(contents)

            candidates = res.get("candidates", [])
            if not candidates:
                return "No candidate response from Gemini."

            parts = candidates[0].get("content", {}).get("parts", [])

            fn_call = None
            text_resp = ""
            for p in parts:
                if "functionCall" in p:
                    fn_call = p["functionCall"]
                if "text" in p:
                    text_resp += p["text"]

            if not fn_call:
                print(f"✅ Mission complete (Powered by {self.active_model})!\n")
                return text_resp.strip()

            contents.append({
                "role": "model",
                "parts": candidates[0]["content"].get("parts", [{"functionCall": fn_call}])
            })

            fn_name = fn_call["name"]
            fn_args = fn_call.get("args", {})
            print(f"🛠️  Action: {fn_name}({json.dumps(fn_args)})")

            tool_fn = self.tools.get(fn_name)
            if not tool_fn:
                result = {"error": f"Tool '{fn_name}' not found."}
            else:
                result = tool_fn(**fn_args)

            status = result.get("status", "done")
            print(f"👀 Observation: {status}")

            # Role MUST be 'user' for Gemini REST API function responses
            contents.append({
                "role": "user",
                "parts": [{
                    "functionResponse": {
                        "name": fn_name,
                        "response": {
                            "name": fn_name,
                            "content": result
                        }
                    }
                }]
            })

        return "Reached max steps."

print("✅ TravelAgent engine ready!")

