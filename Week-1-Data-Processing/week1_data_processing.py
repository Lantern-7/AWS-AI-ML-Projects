# 3. Load the raw dataset
raw_data = [
    ["ID", "Age", "Salary", "Department"],
    ["1", "25", "50000", "Engineering"],
    ["2", "30", "60000", "Marketing"],
    ["3", "unknown", "55000", "Engineering"],  # Messy age
    ["4", "40", "", "Sales"],                  # Missing salary
    ["5", "35", "70000", "Engineering"],
    ["6", "22", "45000", ""],                  # Missing department
]

print("Raw data loaded. Total rows:", len(raw_data))

# 4. Clean it using functions
def clean_number(value, default_value):
    try:
        return float(value)
    except ValueError:
        return default_value

def clean_dataset(data):
    cleaned_data = []
    # Skip the header (index 0) and process the rest
    for row in data[1:]:
        record_id = int(row[0])
        age = clean_number(row[1], default_value=0.0)
        salary = clean_number(row[2], default_value=0.0)
        department = row[3] if row[3] != "" else "Unknown"
        cleaned_data.append([record_id, age, salary, department])
    return cleaned_data

cleaned_data = clean_dataset(raw_data)
print("✅ Data cleaned. Result:")
for row in cleaned_data:
    print(row)

# 5. Process it with NumPy
import numpy as np

# Extract just the Age and Salary columns
numeric_data = [[row[1], row[2]] for row in cleaned_data]
data_array = np.array(numeric_data)

print("NumPy Array shape:", data_array.shape)

# Calculate averages
avg_age = np.mean(data_array[:, 0])
avg_salary = np.mean(data_array[:, 1])

print(f"Average Age: {avg_age:.1f}")
print(f"Average Salary: ${avg_salary:.2f}")

# Filter high earners
high_earners = data_array[data_array[:, 1] > 52000]
print("\nHigh earners (Age, Salary):")
print(high_earners)

